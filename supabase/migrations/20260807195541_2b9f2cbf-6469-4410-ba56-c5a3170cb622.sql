--
-- COALESCE means existing non-null values always win: this only fills gaps.
-- SAFE TO RE-RUN. Fully idempotent. Requires no unique constraint on name.
--
-- Verified 2026-08-07 against the live schema: all_primary_muscles and
-- secondary_muscles are TEXT, pipe-delimited (see src/lib/muscle-map.ts), NOT
-- text[]; image_url holds absolute raw.githubusercontent.com URLs.
