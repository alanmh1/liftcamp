--
-- WHY UPDATE RATHER THAN RE-INSERT. The surviving stubs may now carry logged
-- workout history. Re-inserting the seed rows would recreate the duplicates and
-- split history across two ids. This backfills the surviving rows in place, so
-- ids never change and nothing needs repointing.
